export function tokensJson() {
  return {
    name: 'Вэбтех — презентации',
    version: 1,
    color: {
      themes: [{ id: 'light', name: 'Светлая' }],
      tokens: colors,
    },
    type: { fonts, families, groups: typeGroups },
    spacing: { tokens: spacing },
    radius: { tokens: radius },
    shadow: { tokens: shadow },
    layout: { note: 'Холст слайда и сетка. Все размеры компонентов даны в пикселях холста 1920×1080.', tokens: layout },
  };
}

// CSS для автономных шаблонов (в артефакте tokens.css генерирует страница).
export function tokensCss() {
  const byName = Object.fromEntries(colors.map((t) => [t.name, t.value]));
  const val = (v) => (v.startsWith('{') ? `var(--${v.slice(1, -1)})` : v);
  let out = `@font-face{font-family:"Manrope";src:url("fonts/Manrope-Variable.woff2") format("woff2");font-weight:200 800;font-style:normal;font-display:swap}\n:root{\n`;
  for (const t of colors) out += `  --${t.name}: ${val(t.value)};\n`;
  for (const t of [...spacing, ...radius, ...shadow, ...layout]) out += `  --${t.name}: ${t.value};\n`;
  out += `  --font-sans: ${families.sans};\n}\n`;
  for (const g of typeGroups)
    for (const st of g.styles)
      out += `.${st.name}{font-family:var(--font-sans);font-size:${st.fontSize};line-height:${st.lineHeight};font-weight:${st.fontWeight}${st.letterSpacing ? `;letter-spacing:${st.letterSpacing}` : ''}}\n`;
  void byName;
  return out;
}
